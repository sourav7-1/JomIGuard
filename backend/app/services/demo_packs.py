"""Judge demo packs and demo plots (synthetic). Files: app/scripts/demo_data/packs/<id>/.

A pack becomes a NEW land owned by the caller, so prepared sample cases are never touched.
Generated by ml/synth/demo_packs.py.
"""

import hashlib
import io
import json
import uuid
import zipfile
from functools import cache
from pathlib import Path

from sqlalchemy.orm import Session

from app.models import DocStatus, DocType, Document, DocumentAuditEvent, Land, User
from app.models.document import DocStep

DATA = Path(__file__).resolve().parents[1] / "scripts" / "demo_data"
PACKS = DATA / "packs"


@cache
def packs() -> dict[str, dict]:
    out = {}
    for f in sorted(PACKS.glob("*/pack.json")):
        pack = json.loads(f.read_text(encoding="utf-8"))
        out[pack["id"]] = pack
    return out


def pack_zip(pack_id: str) -> bytes:
    pack = packs()[pack_id]
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_STORED) as z:  # PNGs are already compressed
        for item in pack["files"]:
            z.write(PACKS / pack_id / item["name"], f"jomiguard-sample-{pack_id}/{item['name']}")
        z.writestr(
            f"jomiguard-sample-{pack_id}/README.txt",
            "নমুনা / SAMPLE: সব নাম, নম্বর ও নথি কৃত্রিম (synthetic). Not real documents.\n",
        )
    return buf.getvalue()


def create_pack_case(db: Session, storage, user: User, pack_id: str) -> tuple[Land, list[Document]]:
    """New land from the pack's location + one uploaded document per file (not yet queued)."""
    pack = packs()[pack_id]
    land = Land(owner_id=user.id, **pack["land"])
    db.add(land)
    db.flush()
    docs = []
    for item in pack["files"]:
        data = (PACKS / pack_id / item["name"]).read_bytes()
        doc_id = uuid.uuid4()
        key = f"pack/{doc_id}/{item['name']}"  # never "demo/": that prefix marks prepared samples
        storage.upload(key, data, "image/png")
        doc = Document(
            id=doc_id, land_id=land.id, owner_id=user.id, doc_type=DocType(item["doc_type"]),
            file_key=key, content_sha256=hashlib.sha256(data).hexdigest(),
            source_type="user_upload", original_filename=item["name"],
            status=DocStatus.uploaded, current_step=DocStep.queued,
        )  # fmt: skip
        db.add(doc)
        db.add(
            DocumentAuditEvent(
                document_id=doc_id,
                event="uploaded",
                actor=str(user.id),
                details={"source_type": "user_upload", "demo_pack": pack_id},
            )
        )
        docs.append(doc)
    return land, docs


# Demo plots for the satellite check. Bhola's outline is the recorded demo plot; Gazipur is a
# small square used by the satellite tests' fixtures area.
def plots() -> dict[str, dict]:
    bhola = json.loads((DATA / "satellite_bhola.json").read_text(encoding="utf-8"))["geometry"]
    ring = [[90.41, 23.99], [90.412, 23.99], [90.412, 23.992], [90.41, 23.992], [90.41, 23.99]]
    bhola_land = {"district": "ভোলা", "upazila": "ভোলা সদর", "mouza": "চর মেঘনা (নমুনা প্লট)"}
    gazipur_land = {"district": "গাজীপুর", "upazila": "গাজীপুর সদর", "mouza": "নমুনা প্লট"}
    return {
        "bhola": {"geometry": bhola, "land": {**bhola_land, "dag_no": "417", "khatian_no": ""}},
        "gazipur": {
            "geometry": {"type": "Polygon", "coordinates": [ring]},
            "land": {**gazipur_land, "dag_no": "1", "khatian_no": ""},
        },
    }


def create_plot_case(db: Session, user: User, plot_id: str) -> Land:
    plot = plots()[plot_id]
    land = Land(owner_id=user.id, geometry=plot["geometry"], **plot["land"])
    db.add(land)
    db.flush()
    return land
