"""Readable report of the 20 answer-key scenarios: expected vs actual codes and risk.

Usage (Docker/Linux, from ml/, PYTHONPATH=../backend):
    python -m eval.scenario_report [--out ../docs/reviews/scenarios-v1.md]
Same comparison as backend/tests/test_scenarios.py: codes with severity and documents, plus
the risk level; also the number of actions and whether coverage is complete.
"""

import argparse
import json
import sys
from pathlib import Path

from app.services.actions import next_actions
from app.services.risk import assess
from app.services.rules import run_rules

REPO = Path(__file__).resolve().parents[2]
SCENARIOS = REPO / "backend/tests/scenarios"
OUT = REPO / "docs/reviews/scenarios-v1.md"


def evaluate(folder: Path) -> dict:
    sys.path.insert(0, str(REPO / "backend/tests"))  # scenario_loader is a test helper
    from scenario_loader import load_scenario

    case, expected = load_scenario(folder)
    run = run_rules(case)
    assessment = assess(case, run)
    actions = next_actions(case, run, assessment)
    got: dict[str, tuple[str, frozenset]] = {}
    for f in run.findings:
        _, docs = got.get(f.code, (f.status.value, frozenset()))
        got[f.code] = (f.status.value, docs | {s.source_id for s in f.sources})
    want = {
        f["code"]: (f["severity"], frozenset(f["documents"])) for f in expected["expected_findings"]
    }
    # same codes and severities; every expected document cited (a finding may cite more)
    codes_ok = {c: v[0] for c, v in got.items()} == {c: v[0] for c, v in want.items()} and all(
        docs <= got[c][1] for c, (_, docs) in want.items()
    )
    risk_ok = assessment.risk_level == expected["expected_risk"]
    return {
        "id": folder.name,
        "title": expected["title_bn"],
        "expected": sorted(want),
        "actual": sorted(got),
        "codes_ok": codes_ok,
        "expected_risk": expected["expected_risk"],
        "risk": assessment.risk_level,
        "risk_ok": risk_ok,
        "passed": codes_ok and risk_ok and not run.errors,
        "errors": len(run.errors),
        "actions": len(actions),
        "complete": assessment.coverage.complete,
        "expert": expected["needs_expert_check"],
        "differences": {
            code: (want.get(code), got.get(code))
            for code in sorted(set(want) | set(got))
            if not (
                want.get(code)
                and got.get(code)
                and want[code][0] == got[code][0]
                and want[code][1] <= got[code][1]
            )
        },
    }


def markdown(rows: list[dict]) -> str:
    n_pass = sum(r["passed"] for r in rows)
    lines = [
        "# Scenario report v1 (answer key)",
        "",
        "Generated by `ml/eval/scenario_report.py` from `backend/tests/scenarios/`. "
        "A scenario passes when its finding codes (with severity and documents) and its risk "
        "level equal `expected.json`. ✱ = needs expert check.",
        "",
        f"**{n_pass} / {len(rows)} scenarios pass.** "
        f"Risk level correct: {sum(r['risk_ok'] for r in rows)} / {len(rows)}. "
        f"Rule errors: {sum(r['errors'] for r in rows)}. "
        f"Coverage complete: {sum(r['complete'] for r in rows)} / {len(rows)}.",
        "",
        "| # | scenario | expected codes | actual codes | risk (exp → actual) | result "
        "| actions | coverage |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r['id'][:2]} | {r['title']}{' ✱' if r['expert'] else ''} | "
            f"{', '.join(r['expected']) or '—'} | {', '.join(r['actual']) or '—'} | "
            f"{r['expected_risk']} → {r['risk']} | {'pass' if r['passed'] else '**FAIL**'} | "
            f"{r['actions']} | {'complete' if r['complete'] else 'partial'} |"
        )
    failing = [r for r in rows if not r["passed"]]
    if failing:
        lines += ["", "## Differences", ""]
        for r in failing:
            for code, (want, got) in r["differences"].items():
                w = f"{want[0]} on {sorted(want[1])}" if want else "not expected"
                g = f"{got[0]} on {sorted(got[1])}" if got else "not found"
                lines.append(f"- `{r['id']}` `{code}`: expected {w}; actual {g}")
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path, default=OUT)
    a = ap.parse_args()
    rows = [evaluate(p) for p in sorted(SCENARIOS.iterdir()) if p.is_dir()]
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(markdown(rows), encoding="utf-8", newline="\n")
    print(json.dumps({"passed": sum(r["passed"] for r in rows), "total": len(rows)}))
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
